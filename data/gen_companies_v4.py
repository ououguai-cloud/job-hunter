import re

output = []
existing_names = set()

try:
    with open(os.path.join(os.path.dirname(__file__), 'companies.js'), 'r', encoding='utf-8') as f:
        content = f.read()
    existing_names = set(re.findall(r'\[\s*"([^"]+)"', content))
    print(f"已有公司: {len(existing_names)} 家")
except Exception as e:
    print(f"读取companies.js失败: {e}")

added = 0
skipped = 0
platform_idx = 0
pre_count = 0

for industry, companies in COMPANY_NAMES_V4.items():
    defaults = INDUSTRY_DEFAULTS_V4.get(industry, INDUSTRY_DEFAULTS_V4["互联网/科技"])
    for entry in companies:
        if isinstance(entry, tuple):
            name, city = entry
        else:
            name, city = entry, "北京"

        if name in existing_names:
            skipped += 1
            continue
        existing_names.add(name)

        h = hash_str(name)
        ctype = defaults["types"][h % len(defaults["types"])]
        scale = defaults["scales"][(h >> 3) % len(defaults["scales"])]
        salary = defaults["salaries"][(h >> 6) % len(defaults["salaries"])]
        desc = defaults["desc_prefix"]

        if name in OFFICIAL_URLS_V4:
            url = OFFICIAL_URLS_V4[name]
            url_type = "official"
            portal_name = f"{name}招聘官网"
        else:
            platform = PLATFORMS[platform_idx % len(PLATFORMS)]
            platform_idx += 1
            url = platform[1].format(name=name)
            url_type = "thirdparty"
            portal_name = platform[0]

        tier = tier_of(ctype, scale)

        # 预发布标记：约28%的公司为"未来有用人需求"的预发布企业
        if (h >> 10) % 100 < 28:
            pre_release = PRE_MONTHS[(h >> 13) % len(PRE_MONTHS)]
            pre_count += 1
        else:
            pre_release = ""

        output.append({
            "name": name, "industry": industry, "city": city,
            "ctype": ctype, "scale": scale, "salary": salary,
            "url": url, "desc": desc, "tier": tier,
            "urlType": url_type, "portalName": portal_name,
            "preRelease": pre_release,
        })
        added += 1

out_path = os.path.join(os.path.dirname(__file__), 'new_companies_v4.json')
with open(out_path, 'w', encoding='utf-8') as f:
    json.dump(output, f, ensure_ascii=False, indent=2)

