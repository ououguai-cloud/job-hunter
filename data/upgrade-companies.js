// ---------- 规模解析 ----------
function parseScale(s) {
  const m = String(s || '').match(/([\d.]+)\s*万/);
  if (m) return Math.round(parseFloat(m[1]) * 10000);
  const m2 = String(s || '').match(/([\d.]+)\s*k/);
  if (m2) return Math.round(parseFloat(m2[1]) * 1000);
  const m3 = String(s || '').match(/([\d.]+)\s*\+?/);
  return m3 ? parseInt(m3[1], 10) : 0;
}
// ---------- 分级规则 ----------
function tierOf(ctype, scale) {
  const n = parseScale(scale);
  const c = String(ctype || '');
  if (/大厂|龙头|国有大行/.test(c)) return '大厂';
  if (/独角兽/.test(c)) return n >= 5000 ? '大厂' : '中厂';
  if (/世界500强|外企/.test(c)) return n >= 10000 ? '大厂' : (n >= 2000 ? '中厂' : '小厂');
  if (/上市/.test(c)) return n >= 20000 ? '大厂' : (n >= 3000 ? '中厂' : '小厂');
  if (/央企|国企|国有/.test(c)) return n >= 50000 ? '大厂' : (n >= 10000 ? '中厂' : '小厂');
  if (/股份|城商|农商/.test(c)) return n >= 20000 ? '大厂' : (n >= 3000 ? '中厂' : '小厂');
  return n >= 10000 ? '大厂' : (n >= 1000 ? '中厂' : '小厂');
}
