# 读取现有companies.js获取已有公司名
import re
try:
    with open(os.path.join(os.path.dirname(__file__), 'companies.js'), 'r', encoding='utf-8') as f:
        content = f.read()
    # 提取所有公司名（数组中每条的第一个元素）
    existing_names = set(re.findall(r'\[\s*"([^"]+)"', content))
    print(f"已有公司: {len(existing_names)} 家")
except Exception as e:
    print(f"读取companies.js失败: {e}")

# 生成新公司
added = 0
skipped = 0
platform_idx = 0

for industry, companies in COMPANY_NAMES.items():
    defaults = INDUSTRY_DEFAULTS.get(industry, INDUSTRY_DEFAULTS["互联网/科技"])
    for company_entry in companies:
        if isinstance(company_entry, tuple):
            name, city = company_entry
        else:
            name = company_entry
            city = "北京"

        # 去重
        if name in existing_names:
            skipped += 1
            continue
        existing_names.add(name)

        h = hash_str(name)

        # 分配类型/规模/薪资
        ctype = defaults["types"][h % len(defaults["types"])]
        scale = defaults["scales"][(h >> 3) % len(defaults["scales"])]
        salary = defaults["salaries"][(h >> 6) % len(defaults["salaries"])]
        desc = f"{defaults['desc_prefix']}"

        # URL分配
        if name in OFFICIAL_URLS:
            url = OFFICIAL_URLS[name]
            url_type = "official"
            portal_name = f"{name}招聘官网"
        else:
            platform = PLATFORMS[platform_idx % len(PLATFORMS)]
            platform_idx += 1
            url = platform[1].format(name=name)
            url_type = "thirdparty"
            portal_name = platform[0]

        tier = tier_of(ctype, scale)

        output.append({
            "name": name,
            "industry": industry,
            "city": city,
            "ctype": ctype,
            "scale": scale,
            "salary": salary,
            "url": url,
            "desc": desc,
            "tier": tier,
            "urlType": url_type,
            "portalName": portal_name,
        })
        added += 1

