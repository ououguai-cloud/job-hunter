const PAGE_SIZE = 100;
const HOSTS = ['push2delay.eastmoney.com', 'push2.eastmoney.com'];
function apiUrl(host, pn) {
  return `https://${host}/api/qt/clist/get?pn=${pn}&pz=${PAGE_SIZE}&po=1&np=1&fltt=2&invt=2&fid=f20&fs=m:0+t:6,m:0+t:80,m:1+t:2,m:1+t:23,m:0+t:81+s:2048&fields=f12,f14,f100,f102,f20`;
}
async function fetchPage(pn) {
  for (const host of HOSTS) {
    for (let i = 0; i < 3; i++) {
      try {
        const r = await fetch(apiUrl(host, pn), { headers: { 'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) Chrome/126.0' } });
        if (!r.ok) throw new Error('HTTP ' + r.status);
        const j = await r.json();
        if (j && j.data && j.data.diff) return j;
        throw new Error('empty diff');
      } catch (e) {
        if (i === 2) { if (host === HOSTS[HOSTS.length - 1]) throw e; console.log(`    ↳ ${host} 不可用，切换数据源…`); break; }
        await new Promise(r => setTimeout(r, 2500 * (i + 1)));
      }
    }
  }
}

