# 确定性hash函数（与v2一致，保证同名公司数据一致）
# ============================================================
def hash_str(s):
    h = 2166136261
    for c in s:
        h ^= ord(c)
        h = (h * 16777619) & 0xFFFFFFFF
    return h

def tier_of(ctype, scale):
    m = str(scale or '').replace('万', '0000').replace('+', '')
    try:
        n = int(m) if m else 0
    except Exception:
        n = 0
    c = str(ctype or '')
    if '大厂' in c or '龙头' in c or '国有大行' in c or '世界500强' in c:
        return '大厂'
    if '外企' in c or '跨国' in c:
        return '大厂' if n >= 10000 else ('中厂' if n >= 2000 else '小厂')
    if '独角兽' in c:
        return '大厂' if n >= 5000 else '中厂'
    if '上市' in c:
        return '大厂' if n >= 20000 else ('中厂' if n >= 3000 else '小厂')
    if '央企' in c or '国企' in c or '国有' in c:
        return '大厂' if n >= 50000 else ('中厂' if n >= 10000 else '小厂')
    if '股份' in c or '城商' in c or '农商' in c:
        return '大厂' if n >= 20000 else ('中厂' if n >= 3000 else '小厂')
    return '大厂' if n >= 10000 else ('中厂' if n >= 1000 else '小厂')

